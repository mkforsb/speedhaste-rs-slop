#!/usr/bin/env python3
"""Generate crates/core/src/tables.rs from the original (freely released) source:
the cosine table (wcgsl/sincos.asm, stored as 3rd-order differences and
integrated at startup by InitSinCos) and the arctangent table (wcgsl/atantbl.c).
usage: gen_tables.py SRC_DIR OUT.rs"""
import re, sys
src, out = sys.argv[1], sys.argv[2]
cos = []
for line in open(f'{src}/wcgsl/sincos.asm', encoding='latin1'):
    line = line.split(';')[0].strip()
    if line.startswith('DD'):
        for v in line[2:].split(','):
            v = v.strip()
            neg = v.startswith('-')
            v = int(v.lstrip('-').rstrip('hH'), 16)
            cos.append(-v if neg else v)
assert len(cos) == 4096, len(cos)
# InitSinCos: three passes of prefix sums, with 32-bit wraparound.
for _ in range(3):
    for i in range(1, 4096):
        cos[i] = (cos[i] + cos[i - 1] + 2**31) % 2**32 - 2**31
text = open(f'{src}/wcgsl/atantbl.c', encoding='latin1').read()
body = text[text.index('{') + 1:text.index('}')]
atan = [int(x) for x in re.findall(r'\d+', body)]
assert len(atan) == 2049, len(atan)
with open(out, 'w') as f:
    f.write('//! Trigonometric tables from the original game (wcgsl/sincos.asm, wcgsl/atantbl.c).\n')
    f.write('//! Generated by re/scripts/gen_tables.py — do not edit.\n\n')
    f.write('/// Cosine of `i * 16` (65536 = full circle), 2.30 fixed point.\n')
    f.write('#[rustfmt::skip]\npub static COS: [i32; 4096] = [\n')
    for i in range(0, 4096, 8):
        f.write('    ' + ' '.join(f'{v},' for v in cos[i:i + 8]) + '\n')
    f.write('];\n\n/// `atan(i / 2048)` in 65536-per-circle units.\n')
    f.write('#[rustfmt::skip]\npub static ARCTAN: [u16; 2049] = [\n')
    for i in range(0, 2049, 16):
        f.write('    ' + ' '.join(f'{v},' for v in atan[i:i + 16]) + '\n')
    f.write('];\n')
print(cos[0], cos[1024], cos[2048], cos[3072], atan[2048])
